"""Write docs/design/traceability.md: every diagram element mapped to its file and line.

Run from the repository root:  python scripts/traceability.py

It reuses the parser in tests/test_diagram_conformance.py, so the table lists exactly
what the conformance test checks. The output is deterministic, so a clean re-run
leaves git without changes.
"""

import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tests import test_diagram_conformance as conformance  # noqa: E402

OUTPUT = ROOT / "docs" / "design" / "traceability.md"


def relative(path) -> str:
    return Path(path).resolve().relative_to(ROOT).as_posix()


def class_location(cls: type) -> str:
    lines, first = inspect.getsourcelines(cls)
    return f"{relative(inspect.getsourcefile(cls))}:{first}"


def attribute_location(cls: type, name: str) -> str:
    """The line that defines the attribute: a class-level assignment or `self.name =`."""
    lines, first = inspect.getsourcelines(cls)
    patterns = (
        re.compile(rf"^\s{{4}}{re.escape(name)}\s*[:=]"),
        re.compile(rf"^\s{{4}}{re.escape(name)}\s*=\s*db\."),
        re.compile(rf"self\.{re.escape(name)}\s*[:=]"),
        re.compile(rf"^\s*def {re.escape(name)}\("),
    )
    for pattern in patterns:
        for offset, line in enumerate(lines):
            if pattern.search(line):
                return f"{relative(inspect.getsourcefile(cls))}:{first + offset}"
    return class_location(cls)


def method_location(cls: type, name: str) -> str:
    member = inspect.getattr_static(cls, name, None)
    if member is None:
        return "not found"
    func = inspect.unwrap(member.__func__ if hasattr(member, "__func__") else member)
    lines, first = inspect.getsourcelines(func)
    # A decorator line comes first in the source; point at the `def` itself.
    for offset, line in enumerate(lines):
        if line.lstrip().startswith(("def ", "async def ")):
            first += offset
            break
    return f"{relative(inspect.getsourcefile(func))}:{first}"


def use_case_table(use_case: str, classes: dict[str, list[type]]) -> list[str]:
    rows = [
        f"## {use_case}",
        "",
        "| Class | Element | Kind | Location |",
        "| --- | --- | --- | --- |",
    ]
    for box in conformance.parse_class_diagram(use_case).values():
        (cls,) = classes[box.name]
        where = class_location(cls)
        rows.append(f"| {box.name} (`{box.stereotype}`) | {box.name} | class | {where} |")
        for name in box.attributes:
            rows.append(f"| {box.name} | {name} | attribute | {attribute_location(cls, name)} |")
        for method in box.methods:
            params = ", ".join(conformance.expected_parameters(use_case, box, method))
            rows.append(
                f"| {box.name} | {method.name}({params}) | method | "
                f"{method_location(cls, method.name)} |"
            )
    rows.append("")
    return rows


def exceptions_section() -> list[str]:
    rows = [
        "## Documented exception: SEQUENCE_DIAGRAM_PARAMETERS",
        "",
        "Where a class diagram and its sequence diagram disagree, the sequence diagram wins.",
        "These methods take the extra parameters listed, in order, after the class diagram's own.",
        "",
        "| Use case | Class | Method | Extra parameters |",
        "| --- | --- | --- | --- |",
    ]
    for (use_case, class_name, method), extra in sorted(
        conformance.SEQUENCE_DIAGRAM_PARAMETERS.items()
    ):
        rows.append(f"| {use_case} | {class_name} | {method} | {', '.join(extra)} |")
    rows.append("")
    return rows


def build() -> str:
    classes = conformance.app_classes()
    lines = [
        "# Traceability: diagram to code",
        "",
        "Generated by `python scripts/traceability.py`. Do not edit by hand.",
        "Each row maps a class, attribute or method in a use case's class diagram to the",
        "`file:line` where the code defines it.",
        "",
    ]
    for use_case in sorted(conformance.CONFORMING_USE_CASES):
        lines.extend(use_case_table(use_case, classes))
    lines.extend(exceptions_section())
    return "\n".join(lines)


def main() -> None:
    from app import create_app

    with create_app({"TESTING": True, "SQLALCHEMY_DATABASE_URI": "sqlite:///:memory:",
                     "SEED_ON_EMPTY": False, "SECRET_KEY": "traceability"}).app_context():
        text = build()
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {relative(OUTPUT)}")


if __name__ == "__main__":
    main()
